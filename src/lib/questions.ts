/** Picks the same question for everyone on a given day. */
export function questionForDay(day: string) {
  let hash = 0;
  for (const ch of day) hash = (hash * 31 + ch.charCodeAt(0)) >>> 0;
  return QUESTIONS[hash % QUESTIONS.length];
}
