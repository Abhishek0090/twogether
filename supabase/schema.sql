-- Twogether database schema (Postgres / Supabase).
-- Applied by `npm run db:setup`, or paste it into Supabase > SQL Editor > Run.
-- Safe to run again: everything uses IF NOT EXISTS.
-- Times are milliseconds since 1970 (BIGINT). User-picked dates are 'YYYY-MM-DD' text.

CREATE TABLE IF NOT EXISTS couples (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invite_code TEXT UNIQUE,
  anniversary TEXT,
  wallpaper TEXT NOT NULL DEFAULT 'blush',
  -- secret Realtime channel name shared by the two partners (typing, calls, presence)
  channel_key TEXT NOT NULL UNIQUE,
  created_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT NOT NULL UNIQUE, -- always stored lowercase
  name TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  avatar_media_id INTEGER,
  partner_nickname TEXT,
  mood_emoji TEXT,
  mood_text TEXT,
  mood_at BIGINT,
  couple_id INTEGER REFERENCES couples(id) ON DELETE SET NULL,
  last_seen BIGINT,
  -- set by the app's heartbeat while it is on screen; used to decide whether to send a push
  active_until BIGINT NOT NULL DEFAULT 0,
  -- secret Realtime channel name only this user listens on (server -> user events)
  channel_key TEXT NOT NULL UNIQUE,
  created_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS sessions (
  token_hash TEXT PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at BIGINT NOT NULL,
  created_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS media (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uploader_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  file TEXT NOT NULL, -- object path in the Storage bucket
  mime TEXT NOT NULL,
  name TEXT,
  size BIGINT NOT NULL,
  created_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS messages (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  couple_id INTEGER NOT NULL REFERENCES couples(id) ON DELETE CASCADE,
  sender_id INTEGER NOT NULL,
  client_id TEXT,
  type TEXT NOT NULL,
  body TEXT,
  media_id INTEGER REFERENCES media(id) ON DELETE SET NULL,
  meta TEXT,
  reply_to INTEGER,
  view_once INTEGER NOT NULL DEFAULT 0,
  viewed_at BIGINT,
  edited_at BIGINT,
  deleted_at BIGINT,
  created_at BIGINT NOT NULL,
  delivered_at BIGINT,
  read_at BIGINT
);
CREATE INDEX IF NOT EXISTS idx_messages_couple ON messages(couple_id, id);
CREATE INDEX IF NOT EXISTS idx_messages_media ON messages(media_id);
CREATE UNIQUE INDEX IF NOT EXISTS idx_messages_client ON messages(sender_id, client_id);

CREATE TABLE IF NOT EXISTS message_hidden (
  message_id INTEGER NOT NULL REFERENCES messages(id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL,
  PRIMARY KEY (message_id, user_id)
);

CREATE TABLE IF NOT EXISTS reactions (
  message_id INTEGER NOT NULL REFERENCES messages(id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL,
  emoji TEXT NOT NULL,
  created_at BIGINT NOT NULL,
  PRIMARY KEY (message_id, user_id)
);

CREATE TABLE IF NOT EXISTS stars (
  message_id INTEGER NOT NULL REFERENCES messages(id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL,
  created_at BIGINT NOT NULL,
  PRIMARY KEY (message_id, user_id)
);

CREATE TABLE IF NOT EXISTS special_dates (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  couple_id INTEGER NOT NULL REFERENCES couples(id) ON DELETE CASCADE,
  title TEXT NOT NULL,
  date TEXT NOT NULL,
  emoji TEXT NOT NULL,
  yearly INTEGER NOT NULL DEFAULT 1,
  created_by INTEGER NOT NULL,
  created_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS bucket_items (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  couple_id INTEGER NOT NULL REFERENCES couples(id) ON DELETE CASCADE,
  title TEXT NOT NULL,
  done_at BIGINT,
  done_by INTEGER,
  created_by INTEGER NOT NULL,
  created_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS daily_answers (
  couple_id INTEGER NOT NULL REFERENCES couples(id) ON DELETE CASCADE,
  day TEXT NOT NULL,
  user_id INTEGER NOT NULL,
  answer TEXT NOT NULL,
  created_at BIGINT NOT NULL,
  PRIMARY KEY (couple_id, day, user_id)
);

CREATE TABLE IF NOT EXISTS push_subscriptions (
  endpoint TEXT PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  p256dh TEXT NOT NULL,
  auth TEXT NOT NULL,
  created_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS kv (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL
);

-- Login / sign-up / pairing attempt counters (serverless functions share no memory).
CREATE TABLE IF NOT EXISTS rate_limits (
  key TEXT PRIMARY KEY,
  count INTEGER NOT NULL,
  reset_at BIGINT NOT NULL
);

-- The app talks to the database only from the server, with the database password.
-- Turn on Row Level Security with no policies, so Supabase's public REST API cannot read these tables.
ALTER TABLE couples ENABLE ROW LEVEL SECURITY;
ALTER TABLE users ENABLE ROW LEVEL SECURITY;
ALTER TABLE sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE media ENABLE ROW LEVEL SECURITY;
ALTER TABLE messages ENABLE ROW LEVEL SECURITY;
ALTER TABLE message_hidden ENABLE ROW LEVEL SECURITY;
ALTER TABLE reactions ENABLE ROW LEVEL SECURITY;
ALTER TABLE stars ENABLE ROW LEVEL SECURITY;
ALTER TABLE special_dates ENABLE ROW LEVEL SECURITY;
ALTER TABLE bucket_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE daily_answers ENABLE ROW LEVEL SECURITY;
ALTER TABLE push_subscriptions ENABLE ROW LEVEL SECURITY;
ALTER TABLE kv ENABLE ROW LEVEL SECURITY;
ALTER TABLE rate_limits ENABLE ROW LEVEL SECURITY;
